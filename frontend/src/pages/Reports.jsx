import { useState } from 'react'
import { Link } from 'react-router-dom'
import { Download, FileText } from 'lucide-react'
import PageHeader from '../components/PageHeader.jsx'
import Panel from '../components/Panel.jsx'
import Notice, { ErrorNotice } from '../components/Notice.jsx'
import { api } from '../services/api.js'
import { useAnalysis } from '../context/AnalysisContext.jsx'

function download(blob, filename) {
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  URL.revokeObjectURL(url)
}

export default function Reports() {
  const { result, location } = useAnalysis()
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState(null)

  const exportCsv = () => {
    const rows = ['date,value', ...(result.series || []).map((p) => `${p.date},${p.value ?? ''}`)]
    download(new Blob([rows.join('\n')], { type: 'text/csv' }), 'terratrend_timeseries.csv')
  }

  const exportPdf = async () => {
    setBusy(true)
    setError(null)
    try {
      const blob = await api.reportPdf({ analysis: result, location })
      download(blob, 'terratrend_report.pdf')
    } catch (err) {
      setError(err)
    } finally {
      setBusy(false)
    }
  }

  return (
    <div className="space-y-6">
      <PageHeader title="Reports and Downloads" subtitle="Export your analysis with methodology and citations." />

      {!result ? (
        <Notice kind="offline" title="Nothing to export yet">
          Run an analysis in the <Link to="/trend">Trend Analyzer</Link> first.
        </Notice>
      ) : (
        <div className="grid gap-6 md:grid-cols-2">
          <Panel title="CSV time series" subtitle={`${result.series?.length ?? 0} rows from the latest analysis`}>
            <button className="btn-primary" onClick={exportCsv} disabled={!result.series?.length}>
              <Download size={16} aria-hidden /> Download CSV
            </button>
          </Panel>
          <Panel title="Scientific PDF report" subtitle="Charts, statistics, citations, methodology and uncertainty. Generated by the backend.">
            <button className="btn-primary" onClick={exportPdf} disabled={busy}>
              <FileText size={16} aria-hidden /> {busy ? 'Generating…' : 'Generate PDF'}
            </button>
            <div className="mt-3"><ErrorNotice error={error} /></div>
          </Panel>
        </div>
      )}
    </div>
  )
}
